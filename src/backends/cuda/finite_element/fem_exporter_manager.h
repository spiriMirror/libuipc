#pragma once
#include <sim_system.h>
#include <uipc/geometry/geometry.h>
#include <uipc/geometry/simplicial_complex.h>
#include <cuda_tool/cuda_tool.h>
#include <cuda_tool/linear_system.h>

namespace uipc::backend::cuda
{
class FiniteElementMethod;
class FiniteElementElastics;
class FiniteElementConstitution;
class FiniteElementExtraConstitution;

class FEMExporterManager final : public SimSystem
{
  public:
    using SimSystem::SimSystem;

  private:
    friend class FEMSystemFeatureOverrider;

    void do_build() override;

    void get_fem_energy(U64 uid, geometry::Geometry& prim_energy);
    void get_fem_gradient(U64 uid, geometry::Geometry& prim_grad);
    void get_fem_hessian(U64 uid, geometry::Geometry& prim_hess);
    void get_fem_vertex_gradient(U64 uid, geometry::SimplicialComplex& vert_grad);

    vector<U64> get_fem_constitution_uids() const;

    struct ConstitutionLookup
    {
        // index into the FiniteElementElastics offset tables (base + extras)
        SizeT                           elastics_index = ~0ull;
        FiniteElementConstitution*      base           = nullptr;
        FiniteElementExtraConstitution* extra          = nullptr;
        IndexT                          dim            = -1;
        // element range in the per-dim primitive buffers
        SizeT primitive_offset = ~0ull;
        SizeT primitive_count  = 0;
    };

    ConstitutionLookup find_constitution(U64 uid) const;

    // scratch buffers, regenerated by each export
    cuda_tool::DeviceBuffer<Float>              m_energies;
    cuda_tool::DeviceDoubletVector<Float, 3>    m_gradients;
    cuda_tool::DeviceTripletMatrix<Float, 3, 3> m_hessians;
    cuda_tool::DeviceBuffer<Vector3>            m_vertex_gradients;

    // scene time step (dt^2 scaling)
    S<const geometry::AttributeSlot<Float>> m_dt_attr;

    SimSystemSlot<FiniteElementMethod>   m_fem;
    SimSystemSlot<FiniteElementElastics> m_elastics;
};
}  // namespace uipc::backend::cuda
